#!/usr/bin/env python3
"""Lift the comment icons out of a Reader-written file into the source.

Run from the repository root::

    python tools/extract_note_icons.py corpus/"Markup Comment.pdf"

Writes `pdfarranger_qt/noteicons.py`. **The drawings are Reader's**: the
same document made in either application has to look the same, and an
icon is the most visible part of that. Seventeen path
drawings, no text in any of them, measured rather than redrawn.

The colour is taken out, and only the colour. A stream's fills are
matched against the annotation's own `/C`: those are the mark's colour
and become a placeholder the writer fills in, and any other fill is left
alone. Seven of the icons draw a white body under the coloured glyph --
a comment's speech bubble, a key's teeth -- and replacing that white too
turned each of them into a solid block. `/Checkmark` needs no special
case either: the grey its stream hard-codes is not its `/C`, so it stays
grey, which is the Acrobat defect reproduced because a comment made here
and a comment made there have to match.

Nothing imports this tool; it exists so the table can be made again from
the file rather than trusted.
"""

import re
import sys
import textwrap

import pikepdf

#: Where the colour goes in a stream we write out again.
FILL = "%FILL%"


def _uncoloured(body, colour):
    """``body`` with the fills that are ``colour`` replaced by `FILL`.

    Only those. A fill the stream names for itself -- the white a comment's
    bubble is drawn with, `/Checkmark`'s grey -- is the drawing rather than
    the mark, and recolouring it loses the drawing.
    """
    def one(match):
        if len(colour) == 3 and all(
                abs(float(a) - b) < 1e-5
                for a, b in zip(match.group(1).split(), colour)):
            return FILL
        return match.group(0)

    return re.sub(r"([\d.]+ [\d.]+ [\d.]+) rg", one, body)


def icons(path):
    """``(name, width, height, body)`` for every `/Text` icon in a file."""
    found = []
    with pikepdf.open(path) as pdf:
        for page in pdf.pages:
            for annot in page.get("/Annots", []):
                if str(annot.get("/Subtype")) != "/Text":
                    continue
                if "/AP" not in annot or "/N" not in annot["/AP"]:
                    continue
                name = str(annot.get("/Name", ""))
                rect = [float(v) for v in annot["/Rect"]]
                body = bytes(annot["/AP"]["/N"].read_bytes()).decode("latin-1")
                body = _uncoloured(body, [float(v)
                                          for v in annot.get("/C", [])])
                found.append((name, round(rect[2] - rect[0], 4),
                              round(rect[3] - rect[1], 4), body.strip()))
    return found


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) != 1:
        sys.exit(__doc__.splitlines()[0])
    found = icons(argv[0])
    if len(found) != 17:
        sys.exit("expected seventeen icons, found %d" % len(found))
    out = ['"""The icons a comment can be given, as Reader draws them.',
           "",
           "Generated by `tools/extract_note_icons.py` from a file Reader",
           "wrote. Do not edit by hand: run the tool again instead, and say",
           "which file it was run against.",
           "",
           "Each entry is the `/Name` written into the annotation, the size of",
           "the rectangle Reader gives it -- cut to the glyph, so a key is",
           "narrow and a right pointer is short -- and the appearance stream",
           'with its fill colour replaced by %r.' % FILL,
           '"""',
           "",
           "#: Where a mark's colour goes in a stream below.",
           "FILL = %r" % FILL,
           "",
           "#: The empty name is Text Note, which Reader writes by leaving",
           "#: `/Name` out rather than by writing the specification's /Note.",
           "ICONS = {"]
    for name, width, height, body in found:
        out.append("    %r: (%s, %s, (" % (name, width, height))
        # Wrapped on whitespace, which a content stream does not care
        # about: the operators and their operands are untouched, and the
        # drawing is the same drawing. Without it the longest of these is
        # an 846-character line.
        for line in textwrap.wrap(" ".join(body.split()), width=62,
                                  break_long_words=False):
            out.append("        %r" % (line + "\n"))
        out.append("    )),")
    out.append("}")
    out.append("")
    with open("pdfarranger_qt/noteicons.py", "w") as handle:
        handle.write("\n".join(out))
    print("wrote pdfarranger_qt/noteicons.py with %d icons" % len(found))


if __name__ == "__main__":
    main()
